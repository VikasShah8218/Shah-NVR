"""MediaMTX Control API client (v3) and config file rendering."""

from pathlib import Path

import httpx

from settings.settings import settings

MANAGED_PREFIX = "cam-"  # only paths starting with this are managed by the agent


class MediaMTXClient:
    def __init__(self) -> None:
        self._client = httpx.AsyncClient(base_url=settings.mediamtx_api, timeout=5.0)

    async def close(self) -> None:
        await self._client.aclose()

    async def _paged(self, url: str) -> list[dict]:
        items, page = [], 0
        while True:
            r = await self._client.get(url, params={"page": page, "itemsPerPage": 1000})
            r.raise_for_status()
            data = r.json()
            items.extend(data.get("items") or [])
            page += 1
            if page >= int(data.get("pageCount") or 0):
                return items

    async def ping(self) -> bool:
        try:
            r = await self._client.get("/v3/config/global/get")
            return r.status_code == 200
        except httpx.HTTPError:
            return False

    async def version(self) -> str | None:
        try:
            r = await self._client.get("/v3/info")
            if r.status_code == 200:
                return r.json().get("version")
        except httpx.HTTPError:
            pass
        return None

    async def list_config_paths(self) -> dict[str, dict]:
        return {p["name"]: p for p in await self._paged("/v3/config/paths/list")}

    async def list_runtime_paths(self) -> dict[str, dict]:
        return {p["name"]: p for p in await self._paged("/v3/paths/list")}

    async def add_path(self, name: str, conf: dict) -> None:
        r = await self._client.post(f"/v3/config/paths/add/{name}", json=conf)
        r.raise_for_status()

    async def patch_path(self, name: str, conf: dict) -> None:
        r = await self._client.patch(f"/v3/config/paths/patch/{name}", json=conf)
        r.raise_for_status()

    async def delete_path(self, name: str) -> None:
        r = await self._client.delete(f"/v3/config/paths/delete/{name}")
        if r.status_code != 404:
            r.raise_for_status()


